# -*- coding: utf-8 -*-
"""数据恢复工具 `tools/restore_from_view.py` 的替身测试（不需要真实桌面/真实数据）。

现场：`output/raw`、`output/png` 已被清空，但 `output/分类` 的硬链接视图
（9818 个文件、4.4 GiB、带 `.galunpack-view`）完好。工具必须：
  · 只读视图，绝不删/改写视图里的任何文件，标记原样保留；
  · 只建硬链接（零拷贝），不退化成复制；
  · 「目标已链同一文件 → 跳过」与 organize.build_view 语义一致；
  · 目标冲突默认拒绝覆盖，--force 才动；
  · --dry-run 不写盘；--check 给出文件数 + 抽样大小，可验证。
"""
from __future__ import annotations

import importlib.util
import os
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

_spec = importlib.util.spec_from_file_location(
    "restore_from_view", ROOT / "tools" / "restore_from_view.py")
assert _spec is not None and _spec.loader is not None
rfv = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(rfv)


def _make_case(tmp_path: Path):
    """造一份「raw/png 被清空、分类视图完好」的现场，返回 (out, view)。

    清空用**改名**而不是删除：本机有批量删除守卫，测试不该触发它。
    """
    out = tmp_path / "out"
    raw = out / "raw" / "data"
    raw.mkdir(parents=True)
    png = out / "png"
    png.mkdir(parents=True)
    (raw / "a.ks").write_bytes(b"SCRIPT" * 10)
    (raw / "b.ogg").write_bytes(b"AUDIO" * 7)
    (png / "c.png").write_bytes(b"PNG" * 5)

    view = out / "分类"
    view.mkdir(parents=True, exist_ok=True)
    (view / ".galunpack-view").write_text("generated by organize.py\n", encoding="utf-8")
    links = [
        ("其他", "raw", "data/a.ks", raw / "a.ks"),
        ("音频", "raw", "data/b.ogg", raw / "b.ogg"),
        ("图片", "png", "c.png", png / "c.png"),
    ]
    for kind, prefix, rel, src in links:
        dst = view / kind / prefix / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        os.link(src, dst)

    (out / "raw").rename(out / "_raw_kept_by_test")
    (out / "png").rename(out / "_png_kept_by_test")
    return out, view


def _snapshot(view: Path) -> dict:
    """视图里每个文件的 (相对路径, 字节数, 内容) + 标记内容。"""
    return {
        p.relative_to(view).as_posix(): (p.stat().st_size, p.read_bytes())
        for p in sorted(view.rglob("*")) if p.is_file()
    }


def test_iter_view_entries_requires_mark(tmp_path):
    view = tmp_path / "分类"
    (view / "其他" / "raw").mkdir(parents=True)
    (view / "其他" / "raw" / "a.ks").write_bytes(b"x")

    with pytest.raises(rfv.ViewError) as exc:
        rfv.iter_view_entries(view)
    assert ".galunpack-view" in str(exc.value)


def test_restore_rebuilds_raw_and_png_without_touching_view(tmp_path):
    """★核心★ 从视图还原出 raw/ png/，且视图一字节未改。"""
    out, view = _make_case(tmp_path)
    before = _snapshot(view)

    res = rfv.restore(out, view)

    assert res["entries"] == 3
    assert res["linked"] == 3
    assert res["by_prefix"] == {"raw": 2, "png": 1}
    assert res["failed"] == 0 and res["conflicts"] == 0
    assert (out / "raw" / "data" / "a.ks").read_bytes() == b"SCRIPT" * 10
    assert (out / "png" / "c.png").read_bytes() == b"PNG" * 5
    # 是硬链接（同一 inode），不是拷贝
    assert os.path.samefile(out / "raw" / "data" / "a.ks",
                            view / "其他" / "raw" / "data" / "a.ks")
    assert _snapshot(view) == before, "视图必须只读：路径、大小、内容全不变"
    assert (view / ".galunpack-view").read_text(encoding="utf-8") == \
        "generated by organize.py\n"


def test_second_restore_skips_samefile_links(tmp_path):
    """已链同一文件 → 跳过（与 organize.build_view 一致），不 unlink 再 link。"""
    out, view = _make_case(tmp_path)
    rfv.restore(out, view)
    before = _snapshot(view)

    res = rfv.restore(out, view)

    assert res["linked"] == 0
    assert res["skipped_same"] == 3
    assert res["failed"] == 0
    assert _snapshot(view) == before


def test_dry_run_writes_nothing(tmp_path):
    out, view = _make_case(tmp_path)
    before = _snapshot(view)

    res = rfv.restore(out, view, dry_run=True)

    assert res["dry_run"] is True and res["linked"] == 3
    assert not (out / "raw").exists() and not (out / "png").exists()
    assert _snapshot(view) == before


def test_conflicting_target_is_not_overwritten_by_default(tmp_path):
    """目标已存在且不是同一文件：默认拒绝，绝不静默覆盖用户数据。"""
    out, view = _make_case(tmp_path)
    rfv.restore(out, view)
    dst = out / "raw" / "data" / "a.ks"
    dst.unlink()                            # 断开硬链接后再造一个不同文件
    dst.write_bytes(b"USER-NEW-DATA")

    res = rfv.restore(out, view)

    assert res["conflicts"] == 1
    assert dst.read_bytes() == b"USER-NEW-DATA"
    assert res["errors"] and "未覆盖" in res["errors"][0]


def test_force_overwrites_conflict_with_hardlink(tmp_path):
    out, view = _make_case(tmp_path)
    rfv.restore(out, view)
    dst = out / "raw" / "data" / "a.ks"
    dst.unlink()
    dst.write_bytes(b"USER-NEW-DATA")

    res = rfv.restore(out, view, force=True)

    assert res["conflicts"] == 0 and res["failed"] == 0
    assert dst.read_bytes() == b"SCRIPT" * 10
    assert os.path.samefile(dst, view / "其他" / "raw" / "data" / "a.ks")


def test_check_reports_file_counts_and_sample_sizes(tmp_path):
    """恢复方案必须可验证：文件数 + 抽样文件大小 + samefile。"""
    out, view = _make_case(tmp_path)
    rfv.restore(out, view)

    res = rfv.check(out, view, sample=3)

    assert res["raw_files"] == 2 and res["png_files"] == 1
    assert res["expected_raw_from_view"] == 2
    assert res["expected_png_from_view"] == 1
    assert res["raw_bytes"] == len(b"SCRIPT" * 10) + len(b"AUDIO" * 7)
    assert res["png_bytes"] == len(b"PNG" * 5)
    assert res["missing"] == 0
    assert len(res["samples"]) == 3
    assert all(s["ok"] and s["samefile"]
               and s["actual_size"] == s["expected_size"] > 0
               for s in res["samples"])
    assert res["ok"] is True


def test_check_detects_missing_files(tmp_path):
    """没还原就 --check：必须报不通过，不能给假绿。"""
    out, view = _make_case(tmp_path)

    res = rfv.check(out, view, sample=2)

    assert res["raw_files"] == 0 and res["missing"] == 3
    assert res["ok"] is False


def test_cli_dry_run_and_check_exit_codes(tmp_path, capsys):
    out, view = _make_case(tmp_path)
    common = ["--out", str(out)]

    assert rfv.main(common + ["--dry-run"]) == 0
    assert not (out / "raw").exists(), "dry-run 不许写盘"

    assert rfv.main(common) == 0
    assert (out / "raw" / "data" / "a.ks").is_file()

    assert rfv.main(common + ["--check", "--sample", "3", "--json"]) == 0
    assert "raw_files" in capsys.readouterr().out


def test_cli_refuses_unmarked_view(tmp_path, capsys):
    out = tmp_path / "out"
    view = out / "分类" / "其他" / "raw"
    view.mkdir(parents=True)
    (view / "a.ks").write_bytes(b"x")

    assert rfv.main(["--out", str(out)]) == 1
    assert "标记" in capsys.readouterr().out
